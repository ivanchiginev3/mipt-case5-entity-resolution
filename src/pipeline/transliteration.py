def transliterate(text):

    if pd.isna(text):
        return ""

    text = str(text)

    text = unicodedata.normalize("NFKC", text)

    result = []

    for ch in text:

        result.append(
            CHAR_MAP.get(ch, ch)
        )

    text = "".join(result)

    text = text.lower()

    # remove apostrophes
    text = re.sub(r"[`'’]", "", text)

    # normalize spaces
    text = re.sub(r"\s+", " ", text)

    return text.strip()